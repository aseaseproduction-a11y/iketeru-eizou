/**
 * Builds the runtime creator-index overrides from local reading inference.
 * Input: creator_reading_inference.json
 * Output: shared/creatorIndexOverrides.ts
 *
 * The runtime consumes only a first-letter section, never an inferred full
 * reading. This prevents a tentative personal-name reading from being shown
 * to users while still reducing the "他" bucket as requested.
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = "/home/ubuntu/iketeru-eizou";
const inputPath = `${root}/analysis/production_tag_normalization/creator_reading_inference.json`;
const outputPath = `${root}/shared/creatorIndexOverrides.ts`;
const report = JSON.parse(readFileSync(inputPath, "utf8"));

const inferred = Object.fromEntries(
  report.inferred
    .filter((entry) => entry?.name && entry?.section && entry.section !== "他")
    .map((entry) => [entry.name, entry.section]),
);

// Confirmed public spellings can be explicitly documented here when known.
const confirmed = {
  "代田栄介": "さ",
  "平井秀次": "は",
  "土岐 彩乃": "た",
  "WOW inc.": "W",
  "LIGHT THE WAY Inc.": "L",
  "superSymmetry": "S",
};

const entries = Object.entries({ ...inferred, ...confirmed }).sort(([a], [b]) => a.localeCompare(b, "ja"));
const body = `/**\n * 制作者の五十音・ABC見出し上書き。\n * - confirmed: 公式プロフィール等で確認済みの分類\n * - inferred: ローカル形態素解析で推定した分類。全文の読みはUIに表示しない。\n * Generated by scripts/build-creator-index-overrides.mjs\n */\nexport const CREATOR_INDEX_OVERRIDES: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`;
writeFileSync(outputPath, body);
console.log(JSON.stringify({ inferredInputCount: report.inferredCount, overrideCount: entries.length, outputPath }, null, 2));
